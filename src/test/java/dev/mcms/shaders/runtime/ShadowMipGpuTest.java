package dev.mcms.shaders.runtime;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import dev.mcms.metal.MetalBridge;
import dev.mcms.shaders.metal.HeadlessGpu;
import dev.mcms.shaders.pack.ConstValue;
import dev.mcms.shaders.pack.TargetUnion;
import dev.mcms.shaders.runtime.shadow.ShadowTargets;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * The shadow colour buffer's mip chain on the GPU (E5 review item 10): a cleared colour buffer with a requested chain has
 * its level 1 generated by {@link ShadowTargets#fillMips}, the chain is then no longer stale, and a fresh texture's level 1
 * (never generated) would read zero.
 */
@Tag("gpu")
class ShadowMipGpuTest {

	private static final int SIZE = 64;
	private static final int RGBA8 = 70;

	@Test
	void aClearedColourBufferGetsItsMipChainFilledAndNoLongerStale() {
		TargetUnion union = new TargetUnion(Map.of(), Map.of(), Map.of(), Map.of(), Map.of(),
			Map.of("shadowMapResolution", new ConstValue("int", List.of((double) SIZE)),
				"generateShadowColorMipmap", new ConstValue("bool", List.of(1.0)),
				"shadowcolor0ClearColor", new ConstValue("vec4", List.of(0.5, 0.5, 0.5, 1.0))),
			List.of());
		try (HeadlessGpu gpu = new HeadlessGpu()) {
			long enc = gpu.encoder();
			ShadowTargets shadow = new ShadowTargets(union, false, true);
			assertTrue(shadow.create(Targets.engineTextures(gpu.context())), "the device makes the shadow maps");
			try {
				int key = ShadowTargets.keyOfColor(0);
				assertTrue(shadow.mipmappedColor(0), "the pack asks for the colour buffer's chain");
				assertTrue(shadow.mipsStale(key), "a new texture holds no chain yet");
				shadow.clear(enc);
				assertTrue(shadow.fillMips(enc), "the device reduces the colour format");
				MetalBridge.commitAndWait(enc);
				assertFalse(shadow.mipsStale(key), "the chain is filled for the content it holds");

				byte[] level0 = gpu.readTexture(shadow.color(0), 0, 0, SIZE, SIZE, 1, 4);
				assertEquals(128, level0[0] & 0xff, 1, "level 0 holds the clear colour");
				byte[] level1 = gpu.readTexture(shadow.color(0), 0, 1, SIZE / 2, SIZE / 2, 1, 4);
				assertEquals(128, level1[0] & 0xff, 1, "level 1 was generated from level 0");
				assertEquals(128, level1[4 * (SIZE / 2 * SIZE / 2 - 1)] & 0xff, 1, "the last texel of level 1 too");
			} finally {
				shadow.release();
			}
		}
	}
}
